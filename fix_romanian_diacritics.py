def normalize_cedillas(text: str) -> str:
    """Convert legacy cedilla diacritics (ş/ţ) to modern comma-below (ș/ț)."""
    return (
        text.replace("ş", "ș")
        .replace("ţ", "ț")
        .replace("Ş", "Ș")
        .replace("Ţ", "Ț")
    )


TOKEN_RE = re.compile(r"[A-Za-zăâîșțĂÂÎȘȚ]+(?:-[A-Za-zăâîșțĂÂÎȘȚ]+)*", re.UNICODE)


def _apply_case(src: str, replacement: str) -> str:
    if not src:
        return replacement
    if src.isupper():
        return replacement.upper()
    if src[0].isupper():
        return replacement[0].upper() + replacement[1:]
    return replacement


def _build_lookup() -> dict[str, str]:
    lookup: dict[str, str] = {}
    for key, val in sorted(WORD_MAP.items(), key=lambda kv: -len(kv[0])):
        lk = key.casefold()
        if lk not in lookup:
            lookup[lk] = val
    return lookup


